export const toProductSlug = (name) => {
  const direct = productDetails.find((product) => product.name.toLowerCase() === name.toLowerCase());
  if (direct) {
    return direct.slug;
  }

  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
};

export const getProductBySlug = (slug) =>
  productDetails.find((product) => product.slug === slug);
